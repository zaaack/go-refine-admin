package router

import (
	"errors"
	"fmt"
	"net/http"
	"strings"

	"enterprise-admin/backend/config"
	"enterprise-admin/backend/controllers"
	"enterprise-admin/backend/core/actions"
	"enterprise-admin/backend/core/auth"
	"enterprise-admin/backend/core/middleware"
	"enterprise-admin/backend/models"

	"github.com/gin-gonic/gin"
	"github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
	"gorm.io/gorm"

	_ "enterprise-admin/backend/docs" // swagger docs (generated by `swag init`)
)

// rejectBuiltinRole refuses mutation of the built-in admin role (by ids csv).
func rejectBuiltinRole(db *gorm.DB, ids string) error {
	for _, p := range strings.Split(ids, ",") {
		var role models.SysRole
		if err := db.First(&role, strings.TrimSpace(p)).Error; err == nil && role.RoleKey == "admin" {
			return errors.New("内置超级管理员角色不允许修改或删除")
		}
	}
	return nil
}

// Build constructs the gin engine, applies global middleware and registers all
// routes. Both tracks are shown side by side:
//   - Actions mode: sys/* and demo/product are zero-code CRUD resources.
//   - Regular mode: login, order, dashboard, upload, menu tree are hand-written.
func Build(db *gorm.DB) *gin.Engine {
	cfg := config.Get()
	// "dev" is our own flag (e.g. captcha skip); gin only knows these three.
	switch cfg.Server.Mode {
	case gin.DebugMode, gin.ReleaseMode, gin.TestMode:
		gin.SetMode(cfg.Server.Mode)
	}
	r := gin.New()
	r.Use(gin.Logger(), gin.Recovery())
	r.Use(middleware.CORS())
	r.Use(middleware.OperationLog(db))

	// public
	r.GET("/health", func(c *gin.Context) { c.JSON(http.StatusOK, gin.H{"status": "up"}) })
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// ---- Regular mode: auth ----
	// Root /login is the legacy public entry; /api/v1/login is the same
	// handler under the swagger basePath so the generated client works.
	r.POST("/login", controllers.Login(db))
	v1Public := r.Group("/api/v1")
	{
		v1Public.GET("/captcha", controllers.GenerateCaptcha)
		v1Public.POST("/login", controllers.Login(db))
	}
	r.Static("/uploads", "./uploads")

	// ---- Protected API (v1) ----
	v1 := r.Group("/api/v1")
	v1.Use(auth.Middleware())
	{
		v1.GET("/me", controllers.Me)
		v1.GET("/menu/tree", controllers.MenuTree(db))
		v1.GET("/dashboard/stats", controllers.Dashboard(db))
		v1.POST("/upload", controllers.Upload(db, "./uploads"))

		// ---- Actions mode (zero-code CRUD) ----
		hashUserPassword := func(m *models.SysUser) error {
			if m.PlainPassword != "" {
				if err := m.SetPassword(m.PlainPassword); err != nil {
					return err
				}
				m.PlainPassword = "" // never echo it back
			}
			return nil
		}
		actions.NewResource[models.SysUser](db).WithName("sys/user").WithPermPrefix("sys:user").WithHooks(actions.Hooks[models.SysUser]{
			BeforeCreate: func(c *gin.Context, m *models.SysUser) error {
				m.SetCreateBy(auth.GetUserID(c))
				return hashUserPassword(m)
			},
			BeforeUpdate: func(c *gin.Context, m *models.SysUser) error {
				m.SetUpdateBy(auth.GetUserID(c))
				return hashUserPassword(m)
			},
			BeforeList: actions.DataScopeHook[models.SysUser](),
		}).Register(v1)
		actions.NewResource[models.SysRole](db).WithName("sys/role").WithPermPrefix("sys:role").WithHooks(actions.Hooks[models.SysRole]{
			BeforeCreate: func(c *gin.Context, m *models.SysRole) error {
				if m.RoleKey == "admin" {
					return errors.New("角色标识 admin 为内置超级管理员，不可使用")
				}
				return nil
			},
			// The built-in admin role is immutable: it always holds every
			// permission, so editing its grants is meaningless — lock it.
			BeforeUpdate: func(c *gin.Context, m *models.SysRole) error {
				return rejectBuiltinRole(db, c.Param("id"))
			},
			BeforeDelete: func(c *gin.Context, id interface{}) error {
				return rejectBuiltinRole(db, fmt.Sprint(id))
			},
		}).Register(v1)
		actions.NewResource[models.SysMenu](db).WithName("sys/menu").WithPermPrefix("sys:menu").Register(v1)
		actions.NewResource[models.SysDept](db).WithName("sys/dept").WithPermPrefix("sys:dept").Register(v1)
		actions.NewResource[models.SysDict](db).WithName("sys/dict").WithPermPrefix("sys:dict").Register(v1)
		actions.NewResource[models.SysDictDetail](db).WithName("sys/dict-detail").WithPermPrefix("sys:dict-detail").Register(v1)

		// Product: zero-code CRUD, with audit hooks, role data-scope and
		// write-permission guards (F-node perms demo:product:create/edit/delete).
		actions.NewResource[models.Product](db).WithName("demo/product").WithPermPrefix("demo:product").WithHooks(actions.Hooks[models.Product]{
			BeforeCreate: func(c *gin.Context, m *models.Product) error { m.SetCreateBy(auth.GetUserID(c)); return nil },
			BeforeUpdate: func(c *gin.Context, m *models.Product) error { m.SetUpdateBy(auth.GetUserID(c)); return nil },
			BeforeList:   actions.DataScopeHook[models.Product](),
		}).Register(v1)

		// ---- Regular mode (hand-written) ----
		// Hand-written permission checks: RequirePerm middleware and/or inline
		// auth.HasPerm inside the handler.
		order := controllers.OrderController{DB: db}
		v1.GET("/order", order.List)
		v1.POST("/order", auth.RequirePerm("demo:order:create"), order.Create)
		v1.GET("/order/stats", order.Stats)
		v1.PUT("/order/:id/paid", auth.RequirePerm("demo:order:paid"), order.MarkPaid)
		v1.DELETE("/order/:id", auth.RequirePerm("demo:order:delete"), order.Delete)
	}

	return r
}

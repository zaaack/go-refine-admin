import axios, { type AxiosInstance, type AxiosPromise } from "axios";
import {
  ActionsApi,
  AuthApi,
  Configuration,
  DashboardApi,
  OrderApi,
  UploadApi,
  type ResponseEnvelope,
} from "./index";

// Shared axios instance for all generated APIs. URLs stay relative so the Vite
// dev server proxies /api/* to the Go backend (:8080).
export const apiAxios: AxiosInstance = axios.create();

apiAxios.interceptors.request.use((config) => {
  // The generator path-encodes the {resource} param, turning "demo/product"
  // into "demo%2Fproduct", which matches no backend route. Slashes inside the
  // path are safe here (resource names are server-defined), so restore them.
  if (config.url) config.url = config.url.replace(/%2F/gi, "/");
  const t = localStorage.getItem("token");
  if (t) {
    config.headers = config.headers ?? {};
    (config.headers as Record<string, string>)["Authorization"] = `Bearer ${t}`;
  }
  return config;
});

const configuration = new Configuration();

// Singleton API clients generated by openapi-generator (typescript-axios) from
// backend/docs/swagger.json. Regenerate with `pnpm gen:api`; do not edit the
// generated files, put shared logic here instead.
export const actionsApi = new ActionsApi(configuration, undefined, apiAxios);
export const authApi = new AuthApi(configuration, undefined, apiAxios);
export const dashboardApi = new DashboardApi(configuration, undefined, apiAxios);
export const orderApi = new OrderApi(configuration, undefined, apiAxios);
export const uploadApi = new UploadApi(configuration, undefined, apiAxios);

export interface Envelope<T = any> {
  code?: number;
  data?: T;
  msg?: string;
  [k: string]: any;
}

// unwrap resolves the { code, data, msg } envelope, throwing on business-code
// errors so refine surfaces them. The thrown error carries `statusCode` for
// authProvider.onError (401 -> logout).
export async function unwrap<T = any>(p: AxiosPromise<ResponseEnvelope>): Promise<T> {
  const res = await p;
  const env = res.data as Envelope<T>;
  if (env?.code !== 200) {
    const err: any = new Error(env?.msg || `request failed (${res.status})`);
    err.statusCode = env?.code;
    err.response = res;
    throw err;
  }
  return env.data as T;
}

// fetchCaptcha reads the captcha envelope directly: unlike every other
// endpoint the captcha id lives top-level ({ code, data, id }) for
// go-admin compatibility, not inside data.
export async function fetchCaptcha(): Promise<{ id: string; img: string }> {
  const res = await authApi.captchaGet();
  const env = res.data as Envelope<string>;
  if (env?.code !== 200) throw new Error(env?.msg || "验证码获取失败");
  return { id: String((env as any).id ?? ""), img: String(env.data ?? "") };
}
